      let jf = 0;
      function jpegEnd(u, p) {
        const n = u.length;
        let i = p + 2;
        jf = 0;
        while (i + 3 < n) {
          if (u[i] !== 255) return -1;
          let m = u[i + 1];
          if (m === 255) {
            i++;
            continue;
          }
          if (m === 0xd9) return i + 2;
          if (m === 1 || (m >= 0xd0 && m <= 0xd7)) {
            i += 2;
            continue;
          }
          if (
            m >= 0xc0 &&
            m <= 0xcf &&
            m !== 0xc4 &&
            m !== 0xc8 &&
            m !== 0xcc &&
            !jf
          )
            jf = m;
          const len = (u[i + 2] << 8) | u[i + 3];
          i += 2 + len;
          if (m === 0xda) {
            while (i + 1 < n) {
              if (u[i] === 255) {
                const x = u[i + 1];
                if (x === 0 || (x >= 0xd0 && x <= 0xd7)) {
                  i += 2;
                  continue;
                }
                break;
              }
              i++;
            }
          }
        }
        return -1;
      }
      function tiffOrient(u) {
        const le = u[0] === 0x49 && u[1] === 0x49;
        if (!(le || (u[0] === 0x4d && u[1] === 0x4d))) return 0;
        const dv = new DataView(u.buffer, u.byteOffset, u.byteLength);
        try {
          const g16 = (o) => dv.getUint16(o, le),
            g32 = (o) => dv.getUint32(o, le);
          if (g16(2) !== 42 && g16(2) !== 0x55) return 0;
          const ifd = g32(4),
            n = g16(ifd);
          for (let i = 0; i < n; i++) {
            const e = ifd + 2 + i * 12;
            if (g16(e) === 0x112) return g16(e + 8);
          }
        } catch (e) {}
        return 0;
      }
      function jpegList(u) {
        const L = [];
        let p = 0;
        const n = u.length - 3;
        while (p < n) {
          if (u[p] === 255 && u[p + 1] === 216 && u[p + 2] === 255) {
            const e = jpegEnd(u, p);
            if (e > p) {
              if (jf >= 0xc0 && jf <= 0xc2 && e - p > 20000) L.push([p, e]);
              p = e;
              continue;
            }
          }
          p++;
        }
        return L.sort((a, b) => b[1] - b[0] - (a[1] - a[0]));
      }
