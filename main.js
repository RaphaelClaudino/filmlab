      let oh, os, ol;
      function rgb2hsl(r, g, b) {
        const mx = Math.max(r, g, b),
          mn = Math.min(r, g, b),
          d = mx - mn;
        ol = (mx + mn) / 2;
        if (d < 1e-6) {
          oh = 0;
          os = 0;
          return;
        }
        os = d / (1 - Math.abs(2 * ol - 1));
        oh =
          mx === r
            ? (g - b) / d + (g < b ? 6 : 0)
            : mx === g
              ? (b - r) / d + 2
              : (r - g) / d + 4;
        oh *= 60;
      }
      let rr, rg, rb;
      function hsl2rgb(h, s, l) {
        h = ((h % 360) + 360) % 360;
        const c = (1 - Math.abs(2 * l - 1)) * s,
          x = c * (1 - Math.abs(((h / 60) % 2) - 1)),
          m = l - c / 2,
          i = (h / 60) | 0;
        switch (i % 6) {
          case 0:
            rr = c;
            rg = x;
            rb = 0;
            break;
          case 1:
            rr = x;
            rg = c;
            rb = 0;
            break;
          case 2:
            rr = 0;
            rg = c;
            rb = x;
            break;
          case 3:
            rr = 0;
            rg = x;
            rb = c;
            break;
          case 4:
            rr = x;
            rg = 0;
            rb = c;
            break;
          default:
            rr = c;
            rg = 0;
            rb = x;
        }
        rr += m;
        rg += m;
        rb += m;
      }
      function tint(h) {
        hsl2rgb(h, 1, 0.5);
        return [rr - 0.5, rg - 0.5, rb - 0.5];
      }
      function proc(src, dst, w, h, F, u, noise) {
        const P = prep(F),
          s = P.s,
          d = src.data,
          o = dst.data,
          N = w * h,
          k = u.int / 100;
        const [tc, th, ts, tw, tb] = s.t,
          cb = (tb / 100) * 0.12,
          cw = (tw / 100) * 0.12,
          cs = (ts / 100) * 0.25,
          ch = (th / 100) * 0.25,
          cc = 1 + (tc / 100) * 0.5;
        const sat = 1 + (s.sa || 0) / 100,
          bw = s.bw,
          sp = s.sp,
          bal = sp[4] / 200;
        const st1 = tint(sp[0]),
          st2 = tint(sp[2]),
          sa1 = (sp[1] / 100) * 0.5,
          sa2 = (sp[3] / 100) * 0.5,
          stn = (s.st / 100) * 0.08;
        const gr = (s.g[0] / 100) * 0.22 * k + (u.grain / 100) * 0.25;
        const ucon = 1 + u.con / 100,
          usat = 1 + u.sat / 100,
          bri = u.bri / 200,
          warm = u.warm / 500,
          fd = u.fade / 500,
          vig = (u.vig / 100) * 0.6,
          cx = w / 2,
          cy = h / 2,
          md = cx * cx + cy * cy;
        for (let i = 0, p = 0; i < N; i++, p += 4) {
          const r0 = d[p] / 255,
            g0 = d[p + 1] / 255,
            b0 = d[p + 2] / 255;
          let r = r0,
            g = g0,
            b = b0,
            l;
          if (bw) {
            rgb2hsl(r, g, b);
            const gy = clamp(
              (0.299 * r + 0.587 * g + 0.114 * b) * (1 + P.mx[oh | 0] * os),
            );
            r = g = b = gy;
          }
          l = 0.299 * r + 0.587 * g + 0.114 * b;
          const q = 1 - l,
            dl =
              cb * q * q * q +
              cw * l * l * l +
              cs * 4 * l * q * q +
              ch * 4 * l * l * q;
          r = (r + dl - 0.5) * cc + 0.5;
          g = (g + dl - 0.5) * cc + 0.5;
          b = (b + dl - 0.5) * cc + 0.5;
          r = lk(P.R, r);
          g = lk(P.G, g);
          b = lk(P.B, b);
          if (!bw) {
            rgb2hsl(r, g, b);
            if (os > 0) {
              const hi = oh | 0;
              let ns = os * (1 + P.hS[hi]) * sat;
              ns = ns > 1 ? 1 : ns < 0 ? 0 : ns;
              let nl = ol + P.hL[hi] * os;
              nl = nl < 0 ? 0 : nl > 1 ? 1 : nl;
              hsl2rgb(oh + P.hH[hi], ns, nl);
              r = rr;
              g = rg;
              b = rb;
            }
          }
          l = 0.299 * r + 0.587 * g + 0.114 * b;
          const hw = clamp(l + bal),
            sw = 1 - hw;
          if (sa1)
            ((r += st1[0] * sa1 * sw),
              (g += st1[1] * sa1 * sw),
              (b += st1[2] * sa1 * sw));
          if (sa2)
            ((r += st2[0] * sa2 * hw),
              (g += st2[1] * sa2 * hw),
              (b += st2[2] * sa2 * hw));
          if (stn) g -= stn * (1 - l) * (1 - l);
          r = r0 + (clamp(r) - r0) * k;
          g = g0 + (clamp(g) - g0) * k;
          b = b0 + (clamp(b) - b0) * k;
          r += bri + warm;
          g += bri;
          b += bri - warm;
          r = (r - 0.5) * ucon + 0.5;
          g = (g - 0.5) * ucon + 0.5;
          b = (b - 0.5) * ucon + 0.5;
          if (usat !== 1) {
            l = 0.299 * r + 0.587 * g + 0.114 * b;
            r = l + (r - l) * usat;
            g = l + (g - l) * usat;
            b = l + (b - l) * usat;
          }
          if (fd) {
            r = fd + r * (1 - fd);
            g = fd + g * (1 - fd);
            b = fd + b * (1 - fd);
          }
          if (gr) {
            l = 0.299 * r + 0.587 * g + 0.114 * b;
            const n = noise[i] * gr * (1 - Math.abs(l - 0.5) * 1.2);
            r += n;
            g += n;
            b += n;
          }
          if (vig) {
            const x = (i % w) - cx,
              y = ((i / w) | 0) - cy,
              v = 1 - (vig * (x * x + y * y)) / md;
            r *= v;
            g *= v;
            b *= v;
          }
          o[p] = clamp(r) * 255;
          o[p + 1] = clamp(g) * 255;
          o[p + 2] = clamp(b) * 255;
          o[p + 3] = 255;
        }
      }
